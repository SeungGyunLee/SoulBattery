package org.soulbattery.backend.service;

import org.soulbattery.backend.domain.AxisScores;
import org.soulbattery.backend.domain.SoulType;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

@Service
public class AiAnalysisService {

    public static final String PAYWALL_MARKER = "[[PAYWALL]]";

    private final ChatClient chatClient;

    public AiAnalysisService(ChatClient.Builder builder) {
        this.chatClient = builder.build();
    }

    public String getAiComment(SoulType type, AxisScores scores) {
        return chatClient.prompt()
                .user(buildPrompt(type, scores))
                .call()
                .content();
    }

    String buildPrompt(SoulType type, AxisScores s) {
        String common = String.format("""
            당신은 '소울 배터리' 서비스의 마음 에너지 코치입니다.
            사용자는 30개 문항으로 마음 배터리를 점검했습니다. 결과는 세 가지 축으로 나뉩니다.

            [점검 결과]
            - 결과 유형: %s (%s)
            - 겉 배터리 (겉으로 일상을 굴려 가는 힘): %d%%
            - 속 배터리 (속에 실제로 남아 있는 에너지): %d%%
            - 표현 (속 상태를 드러내고 도움을 청하는 정도): %d%%
            - 겉과 속의 차이: %d%%p

            [반드시 지킬 원칙]
            - 이것은 의료적 진단이 아닙니다. '우울증', '장애', '진단' 같은 질병·진단 용어를 쓰지 마세요.
            - 겉과 속의 차이를 핵심으로 해석하세요. 차이가 크다면, 겉으로는 잘 해내고 있어서
              주변도 본인도 소진을 알아차리기 어렵다는 점을 따뜻하게 짚어 주세요.
            - 마크다운 문법(**, *, #)과 이모지를 쓰지 말고, 내담자에게 보내는 편지처럼 차분하게 쓰세요.
            - 제목 없이 바로 본문으로 시작하세요.

            [1부: 지금 상태 읽기]
            - 세 축의 숫자가 어떤 상태를 말해 주는지 4~6줄로 공감하며 풀어 주세요.
            - 끝나면 줄바꿈을 두 번 하세요.

            [2부: 오늘의 작은 충전]
            - '[오늘의 작은 충전]' 이라는 소제목을 적으세요.
            - 오늘 10분 안에 바로 할 수 있는 행동 2가지를 제안하고, 각각 왜 도움이 되는지 2~3줄로 설명하세요.
              가장 낮은 축을 채우는 방향으로 고르세요.
            - 각 행동은 '1.', '2.'로 시작하고, 행동과 행동 사이에는 빈 줄을 하나 넣으세요.
            """, type.title(), type.description(), s.outer(), s.inner(), s.open(), s.gap());

        if (!type.paywallAllowed()) {
            // 속 배터리가 매우 낮은 구간: 결제 구분자 없이, 사람과 연결되는 방향으로 마무리
            return common + """

                [3부: 마무리]
                - 지금은 혼자 버티기보다 믿을 만한 사람이나 전문 상담과 이야기 나누는 것이
                  가장 좋은 충전이라는 점을 부드럽게 권하세요. 겁을 주거나 단정하지 마세요.
                - 따뜻한 응원으로 마무리하세요.
                - 구분자나 유료 안내는 절대 넣지 마세요.
                """;
        }

        return common + """
            - 2부 끝에는 마무리 인사를 하지 마세요.

            [구분자]
            - 줄을 바꾸고 정확히 `%s` 이라고만 입력하세요.

            [3부: 2주 충전 루틴]
            2부가 '오늘 당장 해 볼 작은 행동'이라면, 3부는 2주 동안 따라 하는 실행 계획입니다.
            읽은 사람이 오늘 밤 바로 시작할 수 있을 만큼 구체적이어야 합니다.

            이번 사용자의 중점: %s
            아래 기법 중에서 이 사용자에게 맞는 3가지를 골라, 위 점수에 맞게 구체화하세요.
            %s

            각 루틴은 반드시 아래 형식을 그대로 지키세요. 루틴과 루틴 사이에는 빈 줄을 하나 넣으세요.

            첫 번째 루틴: (루틴 이름)
            - 언제: (요일·시간대·소요 시간을 구체적으로. 예: 매일 밤 11시, 10분)
            - 어떻게: (순서대로 따라 할 수 있게 2~3단계로)
            - 1주차와 2주차: (1주차는 쉽게 시작하고, 2주차에 무엇을 늘리거나 바꾸는지)
            - 왜 도움이 되나: (기법 이름을 밝히고, 이 사용자의 점수와 연결해서 원리를 2문장 이내로)
            - 이렇게 확인해요: (2주 뒤 스스로 변화를 확인할 수 있는 구체적인 기준)
            - 못 한 날에는: (하루를 놓쳤을 때 다시 이어 가는 가장 작은 방법)

            두 번째 루틴: (같은 형식)

            세 번째 루틴: (같은 형식)

            마지막에 빈 줄을 하나 넣고, 2주 뒤 다시 점검해 보자는 말과 함께 응원 1~2문장으로 마무리하세요.

            [3부에서 하지 말 것]
            - 통계, 비율, 연구 결과 수치를 인용하지 마세요. (예: "한국인의 몇 명 중 몇 명이 ~" 같은 문장 금지)
            - "당신만 그런 게 아니에요", "누구나 그럴 수 있어요" 같은 일반적인 위로로 분량을 채우지 마세요.
            - "충분히 쉬세요", "운동을 해 보세요", "긍정적으로 생각해 보세요"처럼 시간·횟수·방법이 없는 조언을 하지 마세요.
            - 2부에서 제안한 행동을 이름만 바꿔 반복하지 마세요.
            """.formatted(PAYWALL_MARKER, focus(s), techniques(s));
    }

    /** 3부 루틴이 집중할 지점: 겉-속 차이가 크면 차이, 아니면 가장 낮은 축 */
    static String focus(AxisScores s) {
        if (s.gap() >= 20) return "겉으로는 해내지만 속이 비어 가는 차이를 줄이기";
        int min = Math.min(s.inner(), Math.min(s.outer(), s.open()));
        if (min == s.inner()) return "속 배터리(즐거움, 의미, 수면, 자기 자비) 채우기";
        if (min == s.outer()) return "겉 배터리(일상을 굴리는 리듬과 실행력) 되살리기";
        return "표현(속 상태를 드러내고 도움을 청하는 힘) 키우기";
    }

    /** 중점에 맞는 근거 기반 기법 후보. 모델이 이 중에서 골라 구체화한다. */
    static String techniques(AxisScores s) {
        if (s.gap() >= 20) return """
            - 할 일 뒤 감정 점수 기록: 일을 끝낼 때마다 기분을 0~10점으로 적어 '해냈는데 비어 있는' 순간을 알아차리기
            - 회복 활동 먼저 예약하기: 일정표에 의무가 아닌 회복 시간을 업무보다 먼저 넣기
            - 성취와 무관한 시간: 주 1~2회, 결과물을 남기지 않는 활동(산책, 낙서, 음악 듣기) 하기
            - 가면 내려놓기 대화: 믿을 만한 한 사람에게 '괜찮아' 대신 실제 상태를 한 문장으로 말하기
            - 행동 활성화: 즐거움을 주는 활동과 작은 성취 활동을 미리 일정에 넣고 실행 후 기분 기록하기
            """;
        int min = Math.min(s.inner(), Math.min(s.outer(), s.open()));
        if (min == s.inner()) return """
            - 행동 활성화: 즐거움을 주는 활동과 작은 성취 활동을 미리 일정에 넣고 실행 후 기분 기록하기
            - 수면 리듬 고정: 매일 같은 기상 시각, 잠들기 30분 전 화면 끄기
            - 자기 자비 연습: 자책이 떠오를 때 친구에게 하듯 스스로에게 쓰는 문장 정해 두기
            - 하루 끝 세 줄 기록: 오늘 의미 있었던 일, 고마웠던 일, 나를 돌본 일 한 줄씩
            """;
        if (min == s.outer()) return """
            - 첫 행동 쪼개기: 미루는 일을 5분 안에 끝나는 첫 행동으로 나누어 시작하기
            - 하루 기준점 고정: 기상, 첫 끼니, 아침 햇빛 쬐기를 매일 같은 시각에
            - 집중과 회복 주기: 50~90분 집중 후 10분은 자리를 떠나 쉬기
            - 거절 문장 준비: 무리한 부탁에 쓸 한 문장을 미리 정해 두고 연습하기
            """;
        return """
            - 감정에 이름 붙이기: 하루 두 번, '피곤하다'보다 구체적인 감정 단어로 기록하기
            - 한 사람에게 한 문장: 믿을 만한 사람에게 실제 상태를 한 문장으로 전하기
            - 걱정 시간 정하기: 하루 15분 정해진 시간에만 걱정을 적고, 그 밖의 시간엔 미뤄 두기
            - 도움 요청 연습: 작은 부탁부터 일주일에 한 번 직접 해 보기
            """;
    }
}
